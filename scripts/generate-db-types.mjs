#!/usr/bin/env node
// Generates src/lookup/supabase/database.types.ts from supabase/migrations (the schema source of truth) by
// applying them to an in-process Postgres (PGlite). Output follows the Supabase CLI `Database` type shape.
// Usage: node scripts/generate-db-types.mjs          (write)
//        node scripts/generate-db-types.mjs --check  (exit 1 if the committed file is out of date)
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { PGlite } from "@electric-sql/pglite";

const root = process.cwd();
const outFile = join(root, "src", "lookup", "supabase", "database.types.ts");
const migrationsDir = join(root, "supabase", "migrations");

const db = new PGlite();
await db.exec(readFileSync(join(root, "supabase", "tests", "supabase-stub.sql"), "utf8"));
for (const file of readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort()) {
  await db.exec(readFileSync(join(migrationsDir, file), "utf8"));
}

const TYPE_MAP = {
  text: "string", varchar: "string", bpchar: "string", uuid: "string", citext: "string",
  timestamptz: "string", timestamp: "string", date: "string", time: "string",
  bool: "boolean",
  int2: "number", int4: "number", int8: "number", float4: "number", float8: "number", numeric: "number",
  json: "Json", jsonb: "Json",
};
const SQL_ARG_MAP = { text: "string", integer: "number", bigint: "number", smallint: "number", boolean: "boolean", uuid: "string", jsonb: "Json" };

const tsType = (udt) => (udt.startsWith("_") ? `${TYPE_MAP[udt.slice(1)] ?? "unknown"}[]` : TYPE_MAP[udt] ?? "unknown");

const { rows: columns } = await db.query(`
  select c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_identity
    from information_schema.columns c
    join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
   where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
   order by c.table_name, c.column_name`);

const { rows: functions } = await db.query(`
  select p.proname as name, pg_get_function_arguments(p.oid) as args, pg_get_function_result(p.oid) as result
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f' and pg_get_function_result(p.oid) <> 'trigger'
   order by p.proname`);

const tables = new Map();
for (const column of columns) {
  if (!tables.has(column.table_name)) tables.set(column.table_name, []);
  tables.get(column.table_name).push(column);
}

const indent = (n) => "  ".repeat(n);
let out = `// Generated by scripts/generate-db-types.mjs from supabase/migrations. Do not edit by hand.
// Regenerate with: npm run db:types

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [table, cols] of tables) {
  const row = cols.map((c) => `${indent(5)}${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`);
  const insert = cols.map((c) => {
    const optional = c.is_nullable === "YES" || c.column_default !== null || c.is_identity === "YES";
    return `${indent(5)}${c.column_name}${optional ? "?" : ""}: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`;
  });
  const update = cols.map((c) => `${indent(5)}${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === "YES" ? " | null" : ""};`);
  out += `${indent(3)}${table}: {
${indent(4)}Row: {
${row.join("\n")}
${indent(4)}};
${indent(4)}Insert: {
${insert.join("\n")}
${indent(4)}};
${indent(4)}Update: {
${update.join("\n")}
${indent(4)}};
${indent(4)}Relationships: [];
${indent(3)}};
`;
}
out += `${indent(2)}};
${indent(2)}Views: { [_ in never]: never };
${indent(2)}Functions: {
`;
for (const fn of functions) {
  const args = fn.args
    ? `{ ${fn.args
        .split(",")
        .map((part) => part.trim().split(/\s+/))
        .map(([name, ...type]) => `${name}: ${SQL_ARG_MAP[type.join(" ")] ?? "unknown"}`)
        .join("; ")} }`
    : "never";
  out += `${indent(3)}${fn.name}: { Args: ${args}; Returns: ${SQL_ARG_MAP[fn.result] ?? "unknown"} };\n`;
}
out += `${indent(2)}};
${indent(2)}Enums: { [_ in never]: never };
${indent(2)}CompositeTypes: { [_ in never]: never };
${indent(1)}};
};
`;

await db.close();

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current !== out) {
    console.error("database.types.ts is out of date. Run: npm run db:types");
    process.exit(1);
  }
  console.log("database.types.ts is up to date.");
} else {
  writeFileSync(outFile, out);
  console.log(`Wrote ${outFile.replace(root + "/", "")} (${tables.size} tables, ${functions.length} functions).`);
}
