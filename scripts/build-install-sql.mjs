#!/usr/bin/env node
// Bundles supabase/migrations into supabase/install/fresh-install.sql: one file to paste into the Supabase SQL Editor
// of a NEW project, run in a single transaction. Existing projects keep applying individual migrations.
// Usage: node scripts/build-install-sql.mjs          (write)
//        node scripts/build-install-sql.mjs --check  (exit 1 if the committed file is out of date)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const migrationsDir = join(root, "supabase", "migrations");
const outFile = join(root, "supabase", "install", "fresh-install.sql");
const files = readdirSync(migrationsDir).filter((file) => file.endsWith(".sql")).sort();

const parts = [
  "-- GENERATED by scripts/build-install-sql.mjs from supabase/migrations. Do not edit; run `npm run db:install-sql`.",
  "-- Fresh Lookup Starter install: paste into Supabase → SQL Editor of a NEW project and run once.",
  "-- Runs every migration in one transaction: either everything is created or nothing is.",
  "-- For an EXISTING project, apply only the missing files from supabase/migrations instead.",
  "",
  "begin;",
  ...files.flatMap((file) => ["", `-- ═══ ${file} ═══`, readFileSync(join(migrationsDir, file), "utf8").trimEnd()]),
  "",
  "commit;",
  "",
];
const content = parts.join("\n");

if (process.argv.includes("--check")) {
  if (!existsSync(outFile) || readFileSync(outFile, "utf8") !== content) {
    console.error("supabase/install/fresh-install.sql is out of date. Run `npm run db:install-sql` and commit the result.");
    process.exit(1);
  }
  console.log(`fresh-install.sql is up to date (${files.length} migrations).`);
} else {
  writeFileSync(outFile, content);
  console.log(`Wrote supabase/install/fresh-install.sql (${files.length} migrations).`);
}
